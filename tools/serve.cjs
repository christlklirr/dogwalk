// Local preview of the app: node tools/serve.cjs, then open http://localhost:8781
const http = require("http"), fs = require("fs"), path = require("path");
const root = require("path").join(__dirname, "..");
const PORT = 8781; // own number, so other projects (often on 8765) do not get in the way
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".png": "image/png", ".webmanifest": "application/manifest+json", ".json": "application/json", ".svg": "image/svg+xml" };
http.createServer((req, res) => {
  let p = decodeURIComponent(new URL(req.url, "http://x").pathname);
  if (p.endsWith("/")) p += "index.html";
  const file = path.join(root, path.normalize(p));
  if (!file.startsWith(path.normalize(root))) return res.writeHead(403).end();
  fs.readFile(file, (err, data) => {
    if (err) return res.writeHead(404).end("not found");
    res.writeHead(200, { "Content-Type": types[path.extname(file)] || "application/octet-stream", "Cache-Control": "no-store" });
    res.end(data);
  });
}).listen(PORT, () => console.log("Wiener Pfotenwege: http://localhost:" + PORT));
